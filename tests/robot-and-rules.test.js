"use strict";
const { test } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const os = require("node:os");
const { rulesPath } = require("../lib/docs");
test("AGENTS.md outranks cloned template and CLAUDE.md, with explicit override highest", (t) => {
  const root=fs.mkdtempSync(path.join(os.tmpdir(),"office-rules-"));
  t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
  const project=path.join(root,"project"),data=path.join(root,"data"),home=path.join(root,"home");
  fs.mkdirSync(project,{recursive:true});fs.mkdirSync(data,{recursive:true});
  fs.mkdirSync(path.join(home,".codex"),{recursive:true});
  const local=path.join(data,"NOI-QUY.md"),claude=path.join(project,"CLAUDE.md");
  const globalAgents=path.join(home,".codex","AGENTS.md"),projectAgents=path.join(project,"AGENTS.md");
  fs.writeFileSync(local,"template");fs.writeFileSync(claude,"claude rules");
  const originalHome=os.homedir;
  os.homedir=()=>home;
  t.after(()=>{os.homedir=originalHome;});
  const cfg={projects:[project],rulesFile:""};
  assert.equal(rulesPath(cfg,data),claude);
  fs.writeFileSync(globalAgents,"global agents rules");
  assert.equal(rulesPath(cfg,data),globalAgents);
  fs.writeFileSync(projectAgents,"project agents rules");
  assert.equal(rulesPath(cfg,data),projectAgents);
  cfg.rulesFile=local;
  assert.equal(rulesPath(cfg,data),local);
});
test("3D model loads only locally and preserves fallback and readable status badges", () => {
  const source=fs.readFileSync(path.join(__dirname,"..","public","index.html"),"utf8");
  assert.match(source,/GLTFLoader/);
  assert.match(source,/assets\/ai_robot\.glb/);
  assert.match(source,/document\.documentElement\.dataset\.robotModel = "fallback"/);
  assert.match(source,/mountRobotModel\(bot\)/);
  assert.match(source,/agent-status state-/);
  assert.match(source,/BADGES =/);
  const ignore=fs.readFileSync(path.join(__dirname,"..",".gitignore"),"utf8");
  assert.match(ignore,/public\/assets\/\*\.glb/);
});
